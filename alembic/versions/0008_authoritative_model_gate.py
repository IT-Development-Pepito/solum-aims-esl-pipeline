ACTIVE_SCOPE_INDEX = "uq_workflow_schedule_active_scope"


def _refuse_schedules_without_a_version() -> None:
    """Abort, naming every schedule the gate would otherwise have to invent a version for."""

    rows = op.get_bind().execute(
        sa.text(
            "SELECT id, workflow_name, store_code FROM workflow_schedule "
            "WHERE configuration_version_id IS NULL ORDER BY created_at, id"
        )
    ).all()
    if not rows:
        return
    listed = "; ".join(f"{row.id} ({row.workflow_name}/{row.store_code})" for row in rows)
    raise RuntimeError(
        "0008_authoritative_model_gate refused: "
        f"{len(rows)} workflow_schedule row(s) have no configuration_version_id: {listed}. "
        "Recreate these schedules with `esl-admin schedules create` so each records the "
        "configuration version it runs under, then rerun the upgrade. "
        "The migration does not assign a version itself."
    )


