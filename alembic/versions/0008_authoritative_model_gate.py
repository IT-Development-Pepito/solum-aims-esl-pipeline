"""Authoritative model gate: required schedule version, active-scope identity, retry due time.

Revision ID: 0008_authoritative_model_gate
Revises: 0007_audit_reconciliation
Create Date: 2026-09-03

Reserved for #21 by the AD-016 plan (Task 8). Additive; three changes:

1. ``workflow_schedule.configuration_version_id`` becomes NOT NULL. The gate
   refuses to run while any schedule lacks a version and names each such row.
   It never inserts a version of its own: a schedule whose configuration is
   unknown is recreated through ``esl-admin schedules create``, which records
   the version it was created under (#15), not patched by a migration.
2. A partial unique index makes the *active* schedule identity per workflow
   and store unique (architecture 5.9). Partial on ``enabled`` so a disabled
   schedule stays as history beside its replacement.
3. ``workflow_execution.retry_not_before`` gives a ``RETRY_WAIT`` execution a
   durable due time, so a retry delay survives a process restart instead of
   living only in the worker's pick interval (#102 recorded limit).
4. ``execution_step.sequence`` gives step attempts a monotonic start order, as
   0007 did for events: a coarse host clock stamps every step of one run with
   the same instant, and the step listing must not then fall to heap order.
"""

